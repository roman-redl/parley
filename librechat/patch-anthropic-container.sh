#!/bin/sh
# Passes the code execution container id back to Anthropic when @librechat/agents sends the next
# request of the same reply.
#
# With web_search_20260209 and later (patch-websearch.sh) the model calls code_execution (dynamic filtering
# of the search results), and the response carries a top-level container { id, expires_at }. When
# the same turn also holds a client tool call (an MCP tool, called in parallel with the server
# tool), the next request of the run sends the client tool result while the code execution
# still has pending tool uses, and Anthropic answers
#   400 invalid_request_error: container_id is required when there are pending tool uses
#   generated by code execution with tools.
# The follow-up request must repeat the container as `container: "<id>"`.
#
# What @librechat/agents (dist/{cjs,esm}/llm/anthropic/index.*, class CustomAnthropic, checked in
# 4.2.7) already does:
#   - invocationParams(options) sends `container: options.container`, but nobody sets it;
#   - the stream parser (utils/message_outputs.*, _makeMessageChunkFromAnthropicEvent) copies
#     everything of message_start.message except content and usage into additional_kwargs, so
#     `container` arrives in additional_kwargs.container of the first chunk, and
#     message_delta.delta likewise (additional_kwargs: { ...delta }), where the container can
#     arrive again; the chunks are concatenated into the AI message that goes back to the model
#     in the next request of the run.
# Observed with @langchain/core 1.2.8 (the version of 4.2.7): the concatenation keeps `id` as is
# (the merge overwrites string fields named "id" instead of appending) and appends only the other
# strings, so container.id is intact and only container.expires_at comes out doubled; the id is
# the only field used here.
#
# The patch, in the cjs and esm builds:
#   1. adds one helper, _withCurrentTurnContainer(messages, options), before _toolsInParams. When
#      options.container is not set it takes the container id from the input messages and
#      returns options with `container: id`. Only the current turn is searched: the AI messages
#      after the last human message, the latest one that has additional_kwargs.container.id (or
#      response_metadata.container.id); a container from an earlier turn is never reused, because
#      it may have expired and the earlier turns have no pending tool uses. Human messages that
#      @librechat/agents injects inside a turn (additional_kwargs.injected, or source "hook",
#      "routing", "handoff" or "steer": hook contexts after tool results, handoff cues, steering)
#      do not end the turn; any other human message does, so an unknown kind of message falls
#      back to the old behaviour (no container) rather than to a stale one. An id that is exactly
#      a repetition of a shorter container_... id (a merge that appends strings) is collapsed to
#      the shorter one;
#   2. _streamChatModelEvents and _streamResponseChunks, the two methods that call
#      invocationParams with the input messages, pass the options through the helper. The
#      non-streaming _generate belongs to @langchain/anthropic, not to this package, and is not
#      patched; LibreChat always streams, and _generate with streaming calls
#      _streamResponseChunks.
# The events path (_streamChatModelEvents, convertAnthropicStream) does not copy the container
# into additional_kwargs itself: there the container is found only in messages that the other
# path (_streamResponseChunks, the one LibreChat uses) produced.
#
# Needed only together with patch-websearch.sh. Drop this patch after upgrading to a LibreChat
# whose @librechat/agents passes the container id itself.
#
# The script fails if an expected text is not found exactly once in each file: a LibreChat
# upgrade that changes @librechat/agents must be noticed at build time. Running it twice fails
# too (the helper is already there). The cjs and esm builds hold the same text in the replaced
# blocks (the blocks have no module syntax or build-specific names).
set -eu

DIST="${1:-/app/node_modules/@librechat/agents/dist}"
CJS="$DIST/cjs/llm/anthropic/index.cjs"
ESM="$DIST/esm/llm/anthropic/index.mjs"

fail() {
  echo "patch-anthropic-container: $1" >&2
  exit 1
}

for f in "$CJS" "$ESM"; do
  [ -f "$f" ] || fail "$f not found"
done

# Replace OLD with NEW in a file only if OLD occurs exactly once; then verify the result.
replace_once() {
  file="$1"
  old="$2"
  new="$3"
  what="$4"
  OLD="$old" NEW="$new" node -e '
    const fs = require("fs");
    const [file] = process.argv.slice(1);
    const { OLD, NEW } = process.env;
    const src = fs.readFileSync(file, "utf8");
    const parts = src.split(OLD);
    if (parts.length !== 2) {
      console.error("expected text found " + (parts.length - 1) + " times, need exactly 1");
      process.exit(1);
    }
    fs.writeFileSync(file, parts.join(NEW));
  ' "$file" || fail "$file: $what not found exactly once"

  # Verify: the new text is present exactly once and the old one is gone (or only inside it).
  OLD="$old" NEW="$new" node -e '
    const fs = require("fs");
    const [file] = process.argv.slice(1);
    const { OLD, NEW } = process.env;
    const src = fs.readFileSync(file, "utf8");
    if (src.split(NEW).length !== 2) process.exit(1);
    // OLD may legitimately stay inside NEW (an insertion): then it must occur as often as in NEW.
    if (src.split(OLD).length !== NEW.split(OLD).length) process.exit(2);
  ' "$file" || fail "$file: $what not replaced as expected after the patch"
}

# Texts are indented with tabs, as in the build output.

# 1. The helper, inserted once before the first helper function of the file.
OLD_ANCHOR='function _toolsInParams(params) {'
NEW_ANCHOR='// patch-anthropic-container: repeat the code execution container of the current turn
function _withCurrentTurnContainer(messages, options) {
	if (options?.container != null || !Array.isArray(messages)) return options;
	const typeOf = (message) => typeof message?.getType === "function" ? message.getType() : message?.type;
	const endsTurn = (message) => {
		const kwargs = message?.additional_kwargs;
		if (kwargs?.injected === true) return false;
		return !["hook", "routing", "handoff", "steer"].includes(kwargs?.source);
	};
	for (let i = messages.length - 1; i >= 0; i--) {
		const message = messages[i];
		const type = typeOf(message);
		if (type === "human") {
			if (endsTurn(message)) return options;
			continue;
		}
		if (type !== "ai") continue;
		const id = (message.additional_kwargs?.container ?? message.response_metadata?.container)?.id;
		if (typeof id !== "string" || id === "") continue;
		const repeated = /^(container_[A-Za-z0-9_-]+?)\1+$/.exec(id);
		return {
			...options,
			container: repeated ? repeated[1] : id
		};
	}
	return options;
}
function _toolsInParams(params) {'

# 2. The two methods that build the request parameters from the input messages.
OLD_EVENTS='	async *_streamChatModelEvents(messages, options, _runManager) {
		const params = this.invocationParams(options);'
NEW_EVENTS='	async *_streamChatModelEvents(messages, options, _runManager) {
		const params = this.invocationParams(_withCurrentTurnContainer(messages, options));'
OLD_CHUNKS='	async *_streamResponseChunks(messages, options, runManager) {
		this.resetTokenEvents();
		const params = this.invocationParams(options);'
NEW_CHUNKS='	async *_streamResponseChunks(messages, options, runManager) {
		this.resetTokenEvents();
		const params = this.invocationParams(_withCurrentTurnContainer(messages, options));'

for f in "$CJS" "$ESM"; do
  # The anchor stays in the file after the insertion, so a second run must be stopped here.
  ! grep -q "_withCurrentTurnContainer" "$f" || fail "$f: already patched"
  replace_once "$f" "$OLD_ANCHOR" "$NEW_ANCHOR" "first helper function of the file (anchor of the new helper)"
  replace_once "$f" "$OLD_EVENTS" "$NEW_EVENTS" "invocationParams call in _streamChatModelEvents"
  replace_once "$f" "$OLD_CHUNKS" "$NEW_CHUNKS" "invocationParams call in _streamResponseChunks"
done

echo "patch-anthropic-container: the code execution container of the current turn is sent with the next request in $DIST"
